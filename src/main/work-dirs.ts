// Номера сессий терминалов: их выдаёт главный процесс.

let lastSession = 0;

/**
 * Номер новой сессии. Номер выдаёт главный процесс, а не карточка: карточка при перерисовке успевает
 * попросить вторую сессию раньше, чем закроет первую, и по общему идентификатору эти двое перепутались бы.
 */
export function newSession(): number {
  return (lastSession += 1);
}

